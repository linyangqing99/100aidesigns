/* ForgeGUI homepage study. All account interactions stay on this device.
   No production JavaScript, credentials, analytics, or API clients are included. */
(() => {
  'use strict';
  const $ = (selector, root = document) => root.querySelector(selector);
  const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];
  const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
  const host = $('#dialog-host');
  const mobile = $('#mobile-navigation');
  const toggle = $('[aria-label="Toggle navigation"]');
  const menuGlyph = toggle.innerHTML;
  const closeGlyph = $('#auth-signup').content.querySelector('[aria-label="Close auth modal"]').innerHTML;
  let lastFocus = null;
  let toastTimer;
  const exitTimers = new WeakMap();
  function showPopover(element, open, centered = false) {
    clearTimeout(exitTimers.get(element));
    const suffix = centered ? '-centered' : '';
    element.classList.remove('fg-popover-enter' + suffix, 'fg-popover-exit' + suffix);
    if (open) {
      element.hidden = false;
      element.classList.add('fg-popover-enter' + suffix);
    } else if (!element.hidden) {
      element.classList.add('fg-popover-exit' + suffix);
      exitTimers.set(element, setTimeout(() => {element.hidden = true;}, reducedMotion.matches ? 0 : 260));
    }
  }

  // Match the original locale behavior. ?lang=en / ?lang=zh makes comparison repeatable.
  const language = new URLSearchParams(location.search).get('lang') || navigator.language;
  const isChinese = /^zh/i.test(language);
  const english = {
    '开发者': 'Developers', '社区': 'Community', '公司': 'Company', '登录': 'Sign In',
    '招聘': 'Careers', '加入 Discord': 'Join Discord', '博客': 'Blog', '文档': 'Docs',
    '隐私政策': 'Privacy Policy', '服务条款': 'Terms of Service', '开始使用': 'Get Started',
    '电子邮箱': 'Email Address', '密码': 'Password', '已经有账户？': 'Already have an account?',
    '还没有账户？': "Don't have an account?", '在支持中查看更多回答': 'See more answers in Support',
    'ForgeGUI 是什么？适合谁？': 'What is ForgeGUI and who is it for?',
    'ForgeGUI 免费吗？': 'Is ForgeGUI free?', '什么是积分？如何使用？': 'What are credits and how do I use them?',
    'ForgeGUI 还能在哪里使用？': 'Where else can I use ForgeGUI?',
    'ForgeGUI 生成的资源许可证是什么？': 'What is the license for assets generated by ForgeGUI?',
    '我可以用自己的资源作为参考吗？': 'Can I use my own assets as reference?'
  };
  function localize(root) {
    if (isChinese) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      const original = node.textContent.trim();
      if (english[original]) node.textContent = node.textContent.replace(original, english[original]);
    }
    $$('[placeholder]', root).forEach(input => {
      input.placeholder = english[input.placeholder] || input.placeholder;
    });
  }
  localize(document.body);
  document.documentElement.lang = isChinese ? 'zh-CN' : 'en';

  function toast(message) {
    const element = $('#demo-toast');
    element.textContent = message;
    element.hidden = false;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => { element.hidden = true; }, 4200);
  }
  function scopeNotice() {
    toast(isChinese ? '这是首页前端学习版本，此入口的后续业务页面未接入。' : 'This homepage study does not connect to the destination service.');
  }
  function closeMenus(except) {
    $$('header [aria-haspopup="menu"]').forEach(button => {
      if (button === except) return;
      button.setAttribute('aria-expanded', 'false');
      $('svg', button)?.classList.remove('rotate-180');
      const menu = document.getElementById(button.getAttribute('aria-controls'));
      if (menu) showPopover(menu, false, true);
    });
  }
  function setMobile(open) {
    showPopover(mobile, open);
    toggle.setAttribute('aria-expanded', String(open));
    toggle.innerHTML = open ? closeGlyph : menuGlyph;
    if (!open) {
      $$('button[aria-expanded]', mobile).forEach(button => {
        button.setAttribute('aria-expanded', 'false');
        $('svg', button)?.classList.remove('rotate-180');
        button.nextElementSibling.classList.replace('grid-rows-[1fr]', 'grid-rows-[0fr]');
        button.nextElementSibling.inert = true;
      });
    }
  }
  $$('button[aria-expanded]', mobile).forEach(button => {button.nextElementSibling.inert = true;});

  function closeAuth() {
    if (!host.childElementCount || host.classList.contains('is-closing')) return;
    host.classList.add('is-closing');
    setTimeout(() => {
      host.replaceChildren();
      host.classList.remove('is-closing');
      $('main').inert = false;
      document.body.style.overflow = '';
      lastFocus?.focus({preventScroll: true});
    }, reducedMotion.matches ? 0 : 350);
  }
  function openAuth(mode) {
    if (!host.childElementCount) lastFocus = document.activeElement;
    closeMenus();
    setMobile(false);
    host.replaceChildren($('#auth-' + mode).content.cloneNode(true));
    localize(host);
    const overlay = host.firstElementChild;
    overlay.classList.add('auth-overlay');
    overlay.dataset.mode = mode;
    $('main').inert = true;
    document.body.style.overflow = 'hidden';
    const inputs = $$('input', overlay);
    inputs.forEach(input => {
      input.setAttribute('aria-label', input.placeholder);
      input.name = input.type === 'email' ? 'demo-email' : 'demo-password';
    });
    overlay.addEventListener('click', event => { if (event.target === overlay) closeAuth(); });
    $('form', overlay).addEventListener('submit', event => {
      event.preventDefault();
      let feedback = $('.form-feedback', overlay);
      if (!feedback) {
        feedback = document.createElement('p');
        feedback.className = 'form-feedback';
        feedback.setAttribute('role', 'status');
        $('form', overlay).append(feedback);
      }
      const passwords = inputs.filter(input => input.type === 'password' || input.dataset.password);
      feedback.textContent = mode === 'signup' && passwords[0]?.value !== passwords[1]?.value
        ? (isChinese ? '两次输入的密码不一致。' : 'Passwords do not match.')
        : (isChinese ? '前端演示完成。没有发送或保存任何信息。' : 'Demo complete. No information was sent or saved.');
    });
    requestAnimationFrame(() => inputs[0]?.focus({preventScroll: true}));
  }

  document.addEventListener('click', event => {
    const button = event.target.closest('button');
    const link = event.target.closest('a');
    if (button?.getAttribute('aria-haspopup') === 'menu') {
      const open = button.getAttribute('aria-expanded') !== 'true';
      closeMenus(button);
      button.setAttribute('aria-expanded', String(open));
      $('svg', button)?.classList.toggle('rotate-180', open);
      const menu = document.getElementById(button.getAttribute('aria-controls'));
      showPopover(menu, open, true);
      return;
    }
    if (button === toggle) { setMobile(toggle.getAttribute('aria-expanded') !== 'true'); return; }
    if (button && mobile.contains(button) && button.hasAttribute('aria-expanded')) {
      const open = button.getAttribute('aria-expanded') !== 'true';
      $$('button[aria-expanded]', mobile).forEach(item => {
        const expanded = item === button && open;
        item.setAttribute('aria-expanded', String(expanded));
        $('svg', item)?.classList.toggle('rotate-180', expanded);
        item.nextElementSibling.classList.toggle('grid-rows-[1fr]', expanded);
        item.nextElementSibling.classList.toggle('grid-rows-[0fr]', !expanded);
        item.nextElementSibling.inert = !expanded;
      });
      return;
    }
    if (!event.target.closest('header')) closeMenus();
    if (button?.getAttribute('aria-label') === 'Scroll to essentials') {
      $('#essentials').scrollIntoView({behavior: reducedMotion.matches ? 'instant' : 'smooth'});
      return;
    }
    if (button && host.contains(button)) {
      const label = button.textContent.trim();
      if (button.getAttribute('aria-label') === 'Close auth modal') return closeAuth();
      if (/^(Show|Hide) password$/.test(button.getAttribute('aria-label') || '')) {
        const showing = button.getAttribute('aria-label') === 'Show password';
        $$('input', host).filter(input => input.type === 'password' || input.dataset.password).forEach(input => {
          input.dataset.password = 'true';
          input.type = showing ? 'text' : 'password';
        });
        button.setAttribute('aria-label', showing ? 'Hide password' : 'Show password');
        return;
      }
      if (label === 'Sign In Instead' || label === 'Back to sign in') return openAuth('login');
      if (label === 'Sign Up Instead') return openAuth('signup');
      if (label === 'Forgot password?') return openAuth('forgot');
      if (label.includes('with Google')) { scopeNotice(); return; }
      return;
    }
    if (button) {
      const label = button.textContent.trim();
      if (['Start Free Now', 'Go to Toolbox', 'Try It Now'].includes(label)) return openAuth('signup');
      if (label === '登录' || label === 'Sign In') return openAuth('login');
      if (label === 'Learn More' && button.closest('#suite')) return openAuth('signup');
      if (label === 'Learn More') return; // These original homepage controls have no action attached.
      if (label === 'See Plans' || button.closest('footer')) {scopeNotice(); return;}
    }
    if (link) {
      const href = link.getAttribute('href');
      if (href === './index.html') {
        event.preventDefault(); setMobile(false);
        $('#hero').scrollIntoView({behavior: reducedMotion.matches ? 'instant' : 'smooth'});
      } else if (href?.startsWith('/')) {
        event.preventDefault(); closeMenus(); setMobile(false);
        if (href === '/toolbox') openAuth('signup');
        else if (href === '/plans') $('#plans').scrollIntoView({behavior: reducedMotion.matches ? 'instant' : 'smooth'});
        else scopeNotice();
      } else if (href?.startsWith('https:')) {
        link.target = '_blank'; link.rel = 'noopener noreferrer'; setMobile(false);
      }
    }
  });
  document.addEventListener('pointerdown', event => {
    if (!event.target.closest('header')) {closeMenus(); if (!mobile.hidden) setMobile(false);}
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape') {
      if (host.childElementCount) closeAuth();
      else {closeMenus(); setMobile(false); toggle.focus({preventScroll:true});}
    }
    if (event.key === 'Tab' && host.childElementCount) {
      const items = $$('button, input, a[href]', host).filter(item => !item.disabled && item.offsetParent !== null);
      if (event.shiftKey && document.activeElement === items[0]) {event.preventDefault(); items.at(-1).focus();}
      else if (!event.shiftKey && document.activeElement === items.at(-1)) {event.preventDefault(); items[0].focus();}
    }
    const menu = event.target.closest('[role="menu"]');
    if (menu && ['ArrowDown','ArrowUp','Home','End'].includes(event.key)) {
      event.preventDefault(); const items = $$('[role="menuitem"]', menu);
      const index = items.indexOf(document.activeElement);
      const next = event.key === 'Home' ? 0 : event.key === 'End' ? items.length-1 : (index + (event.key === 'ArrowDown' ? 1 : -1) + items.length)%items.length;
      items[next].focus();
    }
  });
  matchMedia('(min-width:1170px)').addEventListener('change', () => {closeMenus(); setMobile(false);});

  // Keep the original video files. Only lower-page videos are deferred until near the viewport.
  const videos = $$('video');
  const observer = new IntersectionObserver(entries => entries.forEach(({target, isIntersecting}) => {
    if (isIntersecting && !reducedMotion.matches) {
      if (target.dataset.src && !target.getAttribute('src')) {target.src = target.dataset.src; target.load();}
      target.play().catch(() => {});
    } else target.pause();
  }), {rootMargin: '300px'});
  videos.forEach(video => {video.muted = true; observer.observe(video);});
  reducedMotion.addEventListener('change', () => {
    if (reducedMotion.matches) videos.forEach(video => video.pause());
    else videos.forEach(video => {observer.unobserve(video); observer.observe(video);});
  });
  // Static markup paints immediately. The source's 550 ms logo strike remains visible.
  setTimeout(() => {
    $('#forge-boot')?.classList.add('forge-boot-hide');
    setTimeout(() => {$('#forge-boot')?.remove(); document.documentElement.removeAttribute('data-forge-boot');}, 300);
  }, reducedMotion.matches ? 0 : 550);
})();
